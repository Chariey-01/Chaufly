"""Public, unauthenticated read endpoint backing the family tracking page.

The URL is generated by ``notifications.tracking_url`` and lands in an SMS to the
customer's emergency contact. Treat it as a bearer link: assume it can be
forwarded or guessed, and expose only what a worried relative actually needs.
"""

from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.database import get_db
from app.models import Trip, TripEvent, TripStatus
from app.schemas import PublicTripEvent, PublicTripStatus
from app.services.geo import haversine_km, minutes_for_distance
from app.config import settings

router = APIRouter(tags=["public"])

EMERGENCY_STATES = {TripStatus.SOS}


def mask_plate(plate: str) -> str:
    """Keep a plate recognisable to family, useless to a scraper.

    ``KDA 123A`` -> ``KDA ***A``. A relative can confirm the right car is
    outside; a stranger cannot look up the owner.
    """
    compact = "".join(ch for ch in plate.upper() if ch.isalnum())
    if len(compact) <= 4:
        return "*" * len(compact)
    masked = f"{compact[:3]}{'*' * (len(compact) - 4)}{compact[-1]}"
    if len(masked) == 7:  # Kenyan civilian plate: 3 letters + 3 digits + letter
        return f"{masked[:3]} {masked[3:]}"
    return masked


def _first_name(full_name: str | None) -> str | None:
    if not full_name:
        return None
    return full_name.strip().split()[0]


@router.get("/trips/{trip_id}/public", response_model=PublicTripStatus)
def public_trip_status(trip_id: str, db: Session = Depends(get_db)) -> PublicTripStatus:
    trip = db.get(Trip, trip_id)
    if trip is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Trip {trip_id} not found")

    events = list(
        db.scalars(
            select(TripEvent).where(TripEvent.trip_id == trip_id).order_by(TripEvent.created_at)
        )
    )
    driver = trip.driver

    eta: int | None = None
    if (
        trip.status is TripStatus.DRIVER_EN_ROUTE
        and driver is not None
        and driver.current_lat is not None
        and driver.current_lng is not None
        and trip.pickup_lat is not None
        and trip.pickup_lng is not None
    ):
        approach_km = haversine_km(
            driver.current_lat, driver.current_lng, trip.pickup_lat, trip.pickup_lng
        )
        eta = minutes_for_distance(approach_km, settings.approach_speed_kmh)

    last = events[-1] if events else None

    return PublicTripStatus(
        trip_id=trip.id,
        status=trip.status,
        customer_first_name=_first_name(trip.user_name) or "The passenger",
        driver_first_name=_first_name(driver.full_name) if driver else None,
        driver_rating=round(driver.rating, 2) if driver else None,
        driver_total_trips=driver.total_trips if driver else None,
        driver_certified_manual=(
            driver.transmission_certified.value == "MANUAL_AND_AUTO" if driver else None
        ),
        vehicle=mask_plate(trip.car_registration_plate),
        destination=trip.dropoff_address,
        is_emergency=trip.status in EMERGENCY_STATES,
        payment_status=trip.payment_status,
        created_at=trip.created_at,
        started_at=trip.started_at,
        completed_at=trip.completed_at,
        driver_eta_minutes=eta,
        last_event=last.event_type if last else None,
        last_event_at=last.created_at if last else None,
        events=[PublicTripEvent.model_validate(e) for e in events],
    )
